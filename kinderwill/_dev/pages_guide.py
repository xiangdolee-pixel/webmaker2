def _way(to, icon, title, text, ext=False):
    return f'<a class="way" href="{to}"{_ext if ext else ""}><i>{ic(icon)}</i><b>{title}</b><span>{text}</span>{ic("arr")}</a>'


def _path(start, items):
    """이용 절차의 한 토막 — rows() 와 같은 줄 목록인데 번호를 start + 1 부터 잇는다(토막마다 사진이 곁에 놓인다)"""
